def download_for_geo(geo_id):
    body = {
        "geographyRequest": {
            "startDate": f"01/1/{YEAR}",
            "endDate": f"12/1/{YEAR}",
            "geographyIds": [geo_id],
            "intervalCode": "MQ",
            "geographyMetrics": METRICS,
            "geographyNiches": [{"category": "All", "niche": "All"}],
            "repivotBy": "kpi"
        }
    }

    response = requests.post(
        "https://dac.realpage.com/mac/dd/download/excel/conventional",
        headers=HEADERS,
        json=body
    )

    if response.status_code == 200:
        filename = f"geo_{geo_id}_{YEAR}"
        content_type = response.headers.get("Content-Type", "")
        if content_type in ["application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",  "application/vnd.ms-excel"]:
            with open(f"{filename}.xls" if content_type == "application/vnd.ms-excel" else f"{filename}.xlsx", "wb") as f:
                f.write(response.content)
            print(f"✅ Downloaded {filename}")
        else:
            print(f"Unexpected content type: {content_type}")
    else:
        print(f"❌ Failed for geo_id {geo_id} - Status: {response.status_code}, Message: {response.text}")

